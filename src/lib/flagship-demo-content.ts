type ImgKey = keyof typeof IMG

interface ProductSeed { name: string; category: string; price: number; img: ImgKey; original?: number; tags?: string[]; desc?: string }
export interface FlagshipDemoEntry { brandName: string; tagline: string; categories: string[]; products: Product[] }

function buildProducts(themeId: string, seeds: ProductSeed[]): Product[] {
  return seeds.map((s, i) => ({
    id: `${themeId}-demo-${i + 1}`,
    seller_id: 'demo',
    name: s.name,
    description: s.desc ?? null,
    category: s.category,
    price_inr: s.price,
    original_price_inr: s.original ?? null,
    cost_price_inr: null,
    garment_image_url: _U(IMG[s.img]),
    garment_preprocessed_url: null,
    slug: s.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, ''),
    is_active: true,
    sizes: ['XS', 'S', 'M', 'L', 'XL'],
    colors: ['Black', 'Cream'],
    tags: s.tags ?? [],
    created_at: '',
  }))
}

function entry(themeId: string, brandName: string, tagline: string, categories: string[], seeds: ProductSeed[]): [string, FlagshipDemoEntry] {
  return [themeId, { brandName, tagline, categories, products: buildProducts(themeId, seeds) }]
}

